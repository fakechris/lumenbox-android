package com.lumenopen.lumenbox.push

import com.lumenopen.lumenbox.storage.InstallationConnection
import com.lumenopen.lumenbox.storage.InstallationStore
import java.net.URI
import java.net.URLDecoder
import java.net.URLEncoder
import java.nio.charset.StandardCharsets

/**
 * Target destination parsed from a DingTalk / Feishu notification card button (`lumenbox://open/...`,
 * `docs/110 §5.4`) or a local Android system notification tap.
 */
data class OpenDeepLinkTarget(
    val rawUri: String,
    val connId: String? = null,
    val installationId: String? = null,
    val serverOrigin: String? = null,
    val inboxId: String? = null,
    val conversationId: String? = null,
    val workId: String? = null,
    val seq: Long? = null,
) {
    enum class FocusTab { NEEDS_YOU, CONVERSATIONS, BOARD_DELIVERABLES }

    val preferredTab: FocusTab
        get() = when {
            !inboxId.isNullOrBlank() -> FocusTab.NEEDS_YOU
            !conversationId.isNullOrBlank() -> FocusTab.CONVERSATIONS
            !workId.isNullOrBlank() -> FocusTab.BOARD_DELIVERABLES
            else -> FocusTab.NEEDS_YOU
        }
}

/**
 * Deterministic `lumenbox://open/...` deep-link parser and installation resolver (`docs/110 §5.4`, INV-2259).
 *
 * Supports all DingTalk / Feishu card button & notification deep-link shapes:
 * - Query form: `lumenbox://open?connId=c_org_1&inboxId=appr_42` or `?server=https%3A%2F%2Fhq.example&inbox=appr_42`
 * - Path form:
 *   - `lumenbox://open/inbox/<inboxId>?connId=<connId>`
 *   - `lumenbox://open/<connId>/inbox/<inboxId>`
 *   - `lumenbox://open/<connId>/conversations/<conversationId>`
 *   - `lumenbox://open/<connId>/work/<workId>`
 */
object LumenBoxDeepLinkRouter {
    private val RESERVED_KINDS = setOf("inbox", "approvals", "approval", "conversations", "conversation", "work", "notifications")

    fun parseOpenUri(uriString: String): OpenDeepLinkTarget? {
        val trimmed = uriString.trim()
        if (trimmed.isEmpty()) return null
        val uri = runCatching { URI.create(trimmed) }.getOrNull() ?: return null
        if (!uri.scheme.equals("lumenbox", ignoreCase = true)) return null
        if (!uri.host.equals("open", ignoreCase = true)) return null

        val queryParams = parseQueryParams(uri.rawQuery)
        val segments = (uri.rawPath ?: "")
            .split('/')
            .filter { it.isNotBlank() }
            .map { decodePart(it) }

        var pathConnId: String? = null
        var pathInboxId: String? = null
        var pathConversationId: String? = null
        var pathWorkId: String? = null

        var idx = 0
        if (segments.isNotEmpty() && segments[0].lowercase() !in RESERVED_KINDS) {
            pathConnId = segments[0]
            idx = 1
        }
        if (idx + 1 < segments.size) {
            val resourceKind = segments[idx].lowercase()
            val resourceId = segments[idx + 1].takeIf { it.isNotBlank() }
            when (resourceKind) {
                "inbox", "approval", "approvals" -> pathInboxId = resourceId
                "conversation", "conversations" -> pathConversationId = resourceId
                "work" -> pathWorkId = resourceId
            }
        }

        val connId = queryParams["connId"] ?: queryParams["conn_id"] ?: pathConnId
        val installationId = queryParams["installationId"] ?: queryParams["connectionId"]
        val serverOrigin = queryParams["server"] ?: queryParams["origin"]
        val inboxId = queryParams["inboxId"] ?: queryParams["inbox"] ?: queryParams["approvalId"] ?: pathInboxId
        val conversationId = queryParams["conversationId"] ?: queryParams["conversation"] ?: pathConversationId
        val workId = queryParams["workId"] ?: queryParams["work"] ?: pathWorkId
        val seq = queryParams["seq"]?.toLongOrNull()

        return OpenDeepLinkTarget(
            rawUri = trimmed,
            connId = connId?.takeIf { it.isNotBlank() },
            installationId = installationId?.takeIf { it.isNotBlank() },
            serverOrigin = serverOrigin?.trim()?.trimEnd('/')?.takeIf { it.isNotEmpty() },
            inboxId = inboxId?.takeIf { it.isNotBlank() },
            conversationId = conversationId?.takeIf { it.isNotBlank() },
            workId = workId?.takeIf { it.isNotBlank() },
            seq = seq,
        )
    }

    /**
     * Resolves which local [InstallationConnection] an [OpenDeepLinkTarget] belongs to:
     * matches by `connId` first, then `installationId`, then normalized `serverOrigin` (so DingTalk /
     * Feishu cards generated by an organisation server that only knows its own public HTTPS origin
     * still route directly to the user's matching organisation connection!).
     */
    fun resolveTargetConnection(
        store: InstallationStore,
        target: OpenDeepLinkTarget,
    ): InstallationConnection? {
        target.connId?.let { cid ->
            store.findByConnId(cid)?.let { return it }
        }
        target.installationId?.let { iid ->
            store.findById(iid)?.let { return it }
        }
        target.serverOrigin?.let { origin ->
            val normalizedTarget = origin.trim().trimEnd('/').lowercase()
            store.listConnections().firstOrNull { conn ->
                conn.kind == InstallationConnection.Kind.ORGANISATION &&
                    conn.serverOriginOrRelayUrl.trim().trimEnd('/').lowercase() == normalizedTarget
            }?.let { return it }
        }
        return null
    }

    fun buildNotificationOpenUri(
        connId: String,
        seq: Long,
        inboxId: String? = null,
        conversationId: String? = null,
        workId: String? = null,
    ): String {
        val params = LinkedHashMap<String, String>()
        params["connId"] = connId
        params["seq"] = seq.toString()
        if (!inboxId.isNullOrBlank()) params["inboxId"] = inboxId
        if (!conversationId.isNullOrBlank()) params["conversationId"] = conversationId
        if (!workId.isNullOrBlank()) params["workId"] = workId
        val qs = params.entries.joinToString("&") { (k, v) ->
            "${URLEncoder.encode(k, StandardCharsets.UTF_8.name())}=${URLEncoder.encode(v, StandardCharsets.UTF_8.name())}"
        }
        return "lumenbox://open?$qs"
    }

    private fun parseQueryParams(rawQuery: String?): Map<String, String> {
        if (rawQuery.isNullOrBlank()) return emptyMap()
        val out = LinkedHashMap<String, String>()
        for (pair in rawQuery.split('&')) {
            if (pair.isBlank()) continue
            val eqIdx = pair.indexOf('=')
            if (eqIdx <= 0) continue
            val key = decodePart(pair.substring(0, eqIdx))
            val value = decodePart(pair.substring(eqIdx + 1))
            if (key.isNotEmpty() && !out.containsKey(key)) {
                out[key] = value
            }
        }
        return out
    }

    private fun decodePart(raw: String): String =
        URLDecoder.decode(raw.replace("+", "%2B"), StandardCharsets.UTF_8.name())
}
